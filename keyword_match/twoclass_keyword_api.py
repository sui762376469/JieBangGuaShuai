# 按长度降序排列，实现长关键词优先匹配
SORTED_KEYWORDS = sorted(GROUP_KEYWORDS, key=len, reverse=True)


def is_group_issue(text: str) -> tuple[bool, list[str]]:
    """判断文本是否包含群体性关键词，返回 (是否命中, 命中的关键词列表)"""
    matched = []
    for kw in SORTED_KEYWORDS:
        if kw in text:
            matched.append(kw)
    return len(matched) > 0, matched


def process_csv(input_path: str, output_path: str):
    """
    读取 CSV，对'诉求描述'列做关键词匹配，
    用匹配结果（1/0）覆盖原'标签'列，保存到新文件。
    """
    rows = []
    hit_count = 0
    total_count = 0

    with open(input_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        fieldnames = reader.fieldnames  # 保留原始列名顺序

        for row in reader:
            total_count += 1
            text = row.get('诉求描述', '')
            is_group, matched_kws = is_group_issue(text)

            # 覆盖标签列：命中关键词则为1，否则为0
            row['标签'] = 1 if is_group else 0
            rows.append(row)

            if is_group:
                hit_count += 1
                # print(f"[命中] 行{total_count}: {matched_kws}")

    # 写入新的 CSV 文件
    with open(output_path, 'w', encoding='utf-8', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"\n========== 处理完成 ==========")
    print(f"总行数: {total_count}")
    print(f"命中(标签=1): {hit_count}")
    print(f"未命中(标签=0): {total_count - hit_count}")
    print(f"结果已保存至: {output_path}")


